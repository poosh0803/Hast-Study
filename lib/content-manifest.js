import fs from "node:fs";
import path from "node:path";

const CONTENT_ROOT = path.join(process.cwd(), "content");

// Every content file must `export default` either one set/prompt object,
// or an array of them. That's what makes auto-regeneration below possible:
// the manifest just imports each file's default export and flattens them.
export const SUBJECTS = {
  abstract: { exportName: "ABSTRACT_SETS" },
  math: { exportName: "MATH_SETS" },
  read: { exportName: "READ_SETS" },
  write: { exportName: "WRITE_PROMPTS" },
};

function toIdentifier(filename) {
  const base = filename.replace(/\.js$/, "");
  const cleaned = base.replace(/[^a-zA-Z0-9_$]/g, "_");
  const safe = /^[0-9]/.test(cleaned) ? `_${cleaned}` : cleaned;
  return `content_${safe}`;
}

// Rewrites content/<subject>/manifest.js from scratch based on whatever
// .js files currently sit in that folder. Called after every upload, so
// the manifest never needs a hand edit — see README "Adding study content".
export function regenerateManifest(subject) {
  const config = SUBJECTS[subject];
  if (!config) throw new Error(`Unknown subject: ${subject}`);

  const dir = path.join(CONTENT_ROOT, subject);
  const files = fs
    .readdirSync(dir)
    .filter((f) => f.endsWith(".js") && f !== "manifest.js")
    .sort();

  const idents = files.map(toIdentifier);
  const imports = files.map((file, i) => `import ${idents[i]} from "./${file}";`);

  const header =
    "// Auto-generated by the Upload button (see lib/content-manifest.js).\n" +
    "// Add content via Upload in the app — do not hand-edit this file, it\n" +
    "// gets overwritten on the next upload to this subject.\n\n";

  const body =
    (imports.length ? imports.join("\n") + "\n\n" : "") +
    `export const ${config.exportName} = [${idents.join(", ")}].flat();\n`;

  fs.writeFileSync(path.join(dir, "manifest.js"), header + body, "utf8");
}

// Every uploaded content file across all four subjects, as
// { subject, filename } — used by the Admin tab's remove list.
export function listContentFiles() {
  const files = [];
  for (const subject of Object.keys(SUBJECTS)) {
    const dir = path.join(CONTENT_ROOT, subject);
    const entries = fs
      .readdirSync(dir)
      .filter((f) => f.endsWith(".js") && f !== "manifest.js")
      .sort();
    for (const filename of entries) {
      files.push({ subject, filename });
    }
  }
  return files;
}
